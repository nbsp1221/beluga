import { spawnSync } from 'node:child_process';
import { copyFile, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { URL, fileURLToPath } from 'node:url';

const assets = new URL('../../../packages/ui/src/assets/', import.meta.url);
const desktop = new URL('../', import.meta.url);
const cli = createRequire(import.meta.url).resolve('@tauri-apps/cli/tauri.js');

const [mark, stylesheet] = await Promise.all([
  readFile(new URL('beluga-mark.svg', assets), 'utf8'),
  readFile(new URL('../styles/globals.css', assets), 'utf8'),
]);

const lightTheme = stylesheet.match(/^:root \{([\s\S]*?)^\}/m)?.[1];
const darkTheme = stylesheet.match(/^\.dark \{([\s\S]*?)^\}/m)?.[1];
const light = themeColor(lightTheme, 'primary');
const lightInk = themeColor(lightTheme, 'primary-foreground');
const dark = themeColor(darkTheme, 'primary');

const favicon = mark.replace(
  /^(<svg[^>]*>)/,
  '$1\n  <!-- Generated by apps/desktop/scripts/generate-icons.mjs. -->\n' +
    '  <style>\n' +
    `    svg { color: ${light}; }\n` +
    '    @media (prefers-color-scheme: dark) {\n' +
    `      svg { color: ${dark}; }\n` +
    '    }\n' +
    '  </style>',
);

const tile = mark
  .replace('viewBox=', 'width="64" height="64" viewBox=')
  .replace(
    /^(<svg[^>]*>)/,
    '$1\n  <!-- Generated by apps/desktop/scripts/generate-icons.mjs. -->\n' +
      `  <rect width="64" height="64" rx="15" fill="${toSrgb(light)}"/>`,
  )
  .replace(
    'fill="currentColor"',
    `fill="${toSrgb(lightInk)}" transform="translate(8 8) scale(.75)"`,
  );

const nativeIcons = new URL('src-tauri/icons/', desktop);
const temp = await realpath(tmpdir());
const output = await mkdtemp(join(temp, 'beluga-icons-'));

try {
  const tilePath = join(output, 'source.svg');
  await writeFile(tilePath, tile);
  const generated = spawnSync(process.execPath, [cli, 'icon', tilePath, '--output', output], {
    cwd: fileURLToPath(desktop),
    stdio: 'inherit',
  });

  if (generated.status !== 0) {
    throw generated.error ?? new Error(`Tauri icon failed (${generated.status}).`);
  }

  await Promise.all([
    writeFile(new URL('beluga-favicon.svg', assets), favicon),
    writeFile(new URL('icon.svg', desktop), tile),
    copyFile(join(output, 'icon.ico'), new URL('icon.ico', nativeIcons)),
    copyFile(join(output, 'icon.png'), new URL('icon.png', nativeIcons)),
  ]);
} finally {
  if (dirname(await realpath(output)) === temp) {
    await rm(output, { recursive: true, force: true });
  }
}

function themeColor(theme, role) {
  const color = theme?.match(new RegExp(`--${role}: (oklch\\([^;]+\\));`))?.[1];

  if (!color) {
    throw new Error(`Missing an OKLCH value for --${role} in globals.css.`);
  }

  return color;
}

// Tauri's SVG rasterizer accepts sRGB fills. Use the CSS Color 4 OKLab conversion.
function toSrgb(color) {
  const [lightness, chroma, hue] = color.slice(6, -1).split(' ').map(Number);
  const angle = (hue * Math.PI) / 180;
  const a = chroma * Math.cos(angle);
  const b = chroma * Math.sin(angle);
  const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (lightness - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const channels = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];

  return (
    '#' +
    channels
      .map((channel) => {
        const bounded = Math.min(1, Math.max(0, channel));
        const srgb = bounded <= 0.0031308 ? 12.92 * bounded : 1.055 * bounded ** (1 / 2.4) - 0.055;
        return Math.round(srgb * 255)
          .toString(16)
          .padStart(2, '0');
      })
      .join('')
  );
}
